export const getTranslation = (key, lang = 'vi', vars = {}) => {
    const dict = translations[lang] || translations['vi'];
    let text = dict[key] || translations['vi'][key] || key;
    
    // Substitute template variables e.g. {count}
    for (const [varName, varVal] of Object.entries(vars)) {
        text = text.replace(new RegExp(`\\{${varName}\\}`, 'g'), varVal);
    }
    return text;
};
